<#
.SYNOPSIS
    Builds the web preview: ONE self-contained HTML file (UI, DSP worklet, registry and all factory presets)
    from web/src. Writes web/index.html and docs/index.html (GitHub Pages).
.EXAMPLE
    ./scripts/build-web.ps1                # uses web/src/rig-data.json as is
    ./scripts/build-web.ps1 -RefreshData   # re-export registry + presets from the built test runner first
#>
param(
    [switch] $RefreshData,
    [string] $WorkDir = (Join-Path $env:LOCALAPPDATA 'PedalFaster')
)
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$src  = Join-Path $repo 'web\src'
$utf8 = [Text.UTF8Encoding]::new($false)
function Read-Text([string] $p) { [IO.File]::ReadAllText($p, $utf8) }

$dataFile = Join-Path $src 'rig-data.json'
if ($RefreshData -or -not (Test-Path $dataFile)) {
    $tests = Join-Path $WorkDir 'build\PedalFasterTests_artefacts\Release\PedalFasterTests.exe'
    if (-not (Test-Path $tests)) { throw "Need the test runner to export preset data: $tests (run build.bat)" }
    & $tests --export-web-data $dataFile
    if ($LASTEXITCODE -ne 0) { throw 'export failed' }
}

$version = (Select-String -Path (Join-Path $repo 'CMakeLists.txt') -Pattern 'project\(PedalFaster VERSION ([0-9.]+)').Matches[0].Groups[1].Value
$html    = Read-Text (Join-Path $src 'index.html')
$css     = Read-Text (Join-Path $src 'style.css')
$worklet = Read-Text (Join-Path $src 'dsp-worklet.js')
$app     = Read-Text (Join-Path $src 'app.js')
$data    = (Read-Text $dataFile).Trim().Replace('</', '<\/')
foreach ($code in @($worklet, $app)) { if ($code -match '</script') { throw 'inlined code must not contain </script' } }

$html = $html.Replace('<link rel="stylesheet" href="style.css">', "<style>`n$css`n</style>")
$html = $html.Replace('<script type="text/plain" id="worklet-src" src="dsp-worklet.js"></script>', "<script type=`"text/plain`" id=`"worklet-src`">`n$worklet`n</script>")
$html = $html.Replace('<script src="rig-data.js"></script>', "<script>`n// Effect registry + 250 calibrated factory presets, exported from the C++ build (PedalFasterTests --export-web-data)`nconst RIG_DATA = $data;`n</script>")
$html = $html.Replace('<script src="app.js"></script>', "<script>`n$app`n</script>")
if ($html -match 'src="(dsp-worklet|rig-data|app)\.js"' -or $html -match 'href="style.css"') { throw 'a resource was not inlined' }

$banner = @"
<!--
  Pedal Faster v$version - web preview. ONE self-contained file: UI, DSP (AudioWorklet port of src/dsp) and 250 factory presets.
  GENERATED by scripts/build-web.ps1 from web/src - edit those, not this file.
  Open in Chrome or Edge. start-web.bat serves it on http://localhost (needed by some browsers for screen/system-audio capture).
-->
"@
$html = $html.Replace('<!doctype html>', "<!doctype html>`n$banner")
$html = $html.Replace('<title>Pedal Faster</title>', "<title>Pedal Faster v$version - Web Preview</title>")

foreach ($out in @((Join-Path $repo 'web\index.html'), (Join-Path $repo 'docs\index.html'))) {
    [IO.File]::WriteAllText($out, $html, $utf8)
    Write-Host ("Wrote {0} ({1:N0} KB)" -f $out, ((Get-Item $out).Length / 1KB))
}
