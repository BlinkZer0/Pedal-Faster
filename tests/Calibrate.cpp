// Development tools built into the test runner:
//   --calibrate <file.inc>      measure every factory preset and write per-preset loudness trims
//   --export-factory <dir>      write the factory library as human-readable JSON files (one per preset)
//   --screenshot <file.png>     render the editor to a PNG

#include "TestUtils.h"
#include "presets/FactoryPresets.h"
#include "dsp/Amps/AmpModels.h"
#include "dsp/Cabinets/Cabinet.h"
#ifndef JucePlugin_VersionStringFallback
 #define JucePlugin_VersionStringFallback "1.0.0"
#endif

using namespace pft;

int runCalibration (const juce::File& out)
{
    const double sr = 48000.0;
    const float target = -20.0f;
    auto di = makeGuitarDI (sr, 4.0);
    auto p = makeProcessor (sr, 256);
    juce::String text;
    text << "// Generated by: PedalFasterTests --calibrate (target " << target << " dBFS RMS on the reference DI performance)\n"
         << "static const Calibration kCalibration[] = {\n";
    int n = 0;
    for (auto preset : buildFactoryPresetsUncalibrated())
    {
        preset.limiter.enabled = false; // measure the unlimited level
        float trim = 0.0f;
        for (int iter = 0; iter < 3; ++iter)
        {
            Preset q = preset; q.outputGainDb = std::clamp (preset.outputGainDb + trim, -24.0f, 12.0f);
            loadAndSettle (*p, q);
            auto y = render (*p, di, 256);
            const float lvl = rmsDb (y, (int) (0.1 * sr));
            trim += target - lvl;
            trim = std::clamp (trim, -24.0f - preset.outputGainDb, 12.0f - preset.outputGainDb);
        }
        text << "    { \"" << preset.id << "\", " << juce::String (trim, 2) << "f },\n";
        std::printf ("%-48s %+6.2f dB\n", preset.id.c_str(), trim);
        ++n;
    }
    text << "};\n";
    if (! out.replaceWithText (text)) { std::printf ("could not write %s\n", out.getFullPathName().toRawUTF8()); return 1; }
    std::printf ("calibrated %d presets -> %s\n", n, out.getFullPathName().toRawUTF8());
    return 0;
}

int exportFactory (const juce::File& dir)
{
    dir.createDirectory();
    int n = 0;
    for (auto& b : factoryBanks())
    {
        auto bankDir = dir.getChildFile (juce::String (n / 10 + 1).paddedLeft ('0', 2) + " - " + juce::File::createLegalFileName (b.name));
        (void) bankDir;
    }
    int bankIdx = 0;
    for (auto& b : factoryBanks())
    {
        ++bankIdx;
        auto bankDir = dir.getChildFile (juce::String (bankIdx).paddedLeft ('0', 2) + " " + juce::File::createLegalFileName (b.name).replaceCharacter ('&', '+'));
        bankDir.createDirectory();
        int idx = 0;
        for (auto& p : factoryPresets())
            if (p.category == b.name)
            {
                ++idx;
                auto f = bankDir.getChildFile (juce::String (idx).paddedLeft ('0', 2) + " " + juce::File::createLegalFileName (p.name) + ".json");
                f.replaceWithText (PresetSerializer::toJson (p));
                ++n;
            }
    }
    std::printf ("exported %d presets to %s\n", n, dir.getFullPathName().toRawUTF8());
    return 0;
}

int renderScreenshot (const juce::File& file)
{
    auto p = makeProcessor();
    p->applyPreset (*p->presets().findById ("factory.metal-rhythm.tight-machine"));
    std::unique_ptr<juce::AudioProcessorEditor> ed (p->createEditor());
    ed->setSize (1400, 860);
    auto img = ed->createComponentSnapshot (ed->getLocalBounds(), true, 1.0f);
    juce::PNGImageFormat png;
    file.deleteFile();
    juce::FileOutputStream os (file);
    return png.writeImageToStream (img, os) ? 0 : 1;
}

/** --export-web-data <file.json>: registry, amp/cab names, banks and all calibrated factory presets for the web preview. */
int exportWebData (const juce::File& file)
{
    auto obj = [] { return juce::var (new juce::DynamicObject()); };
    auto set = [] (juce::var& o, const char* k, const juce::var& v) { o.getDynamicObject()->setProperty (k, v); };
    auto strings = [] (const std::vector<std::string>& v) { juce::Array<juce::var> a; for (auto& s : v) a.add (juce::String (s)); return juce::var (a); };

    auto root = obj();
    set (root, "version", juce::String (JucePlugin_VersionStringFallback));
    juce::Array<juce::var> effects;
    for (auto& e : EffectRegistry::get().all())
    {
        auto fx = obj();
        set (fx, "index", e.index); set (fx, "id", juce::String (e.id)); set (fx, "name", juce::String (e.name));
        set (fx, "category", juce::String (e.category)); set (fx, "hasMix", e.hasMix); set (fx, "defaultMix", e.defaultMix);
        juce::Array<juce::var> ps;
        for (auto& p : e.params)
        {
            auto po = obj();
            set (po, "key", juce::String (p.key)); set (po, "name", juce::String (p.name));
            set (po, "min", p.minValue); set (po, "max", p.maxValue); set (po, "def", p.defaultValue);
            set (po, "unit", juce::String (p.unit)); set (po, "log", p.logarithmic); set (po, "int", p.integer);
            if (p.isChoice()) set (po, "choices", strings (p.choices));
            ps.add (po);
        }
        set (fx, "params", ps);
        effects.add (fx);
    }
    set (root, "effects", effects);
    set (root, "ampIds", strings (ampTypeIds())); set (root, "ampNames", strings (ampTypeNames()));
    set (root, "cabIds", strings (cabTypeIds())); set (root, "cabNames", strings (cabTypeNames()));
    juce::Array<juce::var> banks;
    for (auto& b : factoryBanks()) { auto bo = obj(); set (bo, "name", juce::String (b.name)); set (bo, "core", b.core); banks.add (bo); }
    set (root, "banks", banks);
    juce::Array<juce::var> presets;
    for (auto& p : factoryPresets()) presets.add (PresetSerializer::toVar (p));
    set (root, "presets", presets);
    if (! file.replaceWithText (juce::JSON::toString (root, true))) return 1;
    std::printf ("wrote %s (%d presets)\n", file.getFullPathName().toRawUTF8(), presets.size());
    return 0;
}

/** --write-reference-di <file.f32>: the reference DI performance (48 kHz, 4 s, mono raw float32) used for
    calibration and the regression baseline, so the web DSP port can be compared against the C++ engine. */
int writeReferenceDI (const juce::File& file)
{
    auto di = makeGuitarDI (48000.0, 4.0);
    file.deleteFile();
    juce::FileOutputStream os (file);
    if (! os.openedOk()) return 1;
    os.write (di.getReadPointer (0), sizeof (float) * (size_t) di.getNumSamples());
    std::printf ("wrote %s (%d samples)\n", file.getFullPathName().toRawUTF8(), di.getNumSamples());
    return 0;
}
