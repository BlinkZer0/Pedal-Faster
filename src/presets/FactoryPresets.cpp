std::map<std::string, float> kv (const char* s)
{
    std::map<std::string, float> m;
    std::istringstream in (s ? s : "");
    std::string tok;
    while (in >> tok)
    {
        const auto eq = tok.find ('=');
        if (eq == std::string::npos) { m[tok] = std::numeric_limits<float>::quiet_NaN(); continue; } // caught by the validator
        m[tok.substr (0, eq)] = std::stof (tok.substr (eq + 1));
    }
    return m;
}

struct PB
{
    Preset p;
    PB (const char* name, const char* desc, const char* tags)
    {
        p.name = name; p.description = desc; p.factory = true;
        std::stringstream ss (tags); std::string t;
        while (std::getline (ss, t, ',')) if (! t.empty()) p.tags.push_back (t);
    }
    PB& amp (const char* type, const char* params)
    {
        p.amp.type = type;
        for (auto& [k, v] : kv (params))
        {
            if (k == "g") p.amp.gain = v; else if (k == "b") p.amp.bass = v; else if (k == "m") p.amp.mid = v;
            else if (k == "t") p.amp.treble = v; else if (k == "p") p.amp.presence = v; else if (k == "mv") p.amp.master = v;
            else if (k == "s") p.amp.sag = v; else if (k == "trim") p.amp.trimDb = v;
            else p.amp.gain = std::numeric_limits<float>::quiet_NaN();
        }
        return *this;
    }
    PB& noAmp() { p.amp.enabled = false; return *this; }
    PB& cab (const char* type, const char* params = "")
    {
        p.cab.type = type;
        for (auto& [k, v] : kv (params))
        {
            if (k == "mic") p.cab.mic = v; else if (k == "lo") p.cab.lowCutHz = v; else if (k == "hi") p.cab.highCutHz = v;
            else if (k == "lvl") p.cab.levelDb = v; else if (k == "mix") p.cab.mix = v;
            else p.cab.mic = std::numeric_limits<float>::quiet_NaN();
        }
        return *this;
    }
    PB& fx (bool pre, const char* type, const char* params, float mix, bool on)
    {
        EffectState e; e.type = type; e.pre = pre; e.mix = mix; e.enabled = on; e.params = kv (params);
        p.effects.push_back (e);
        return *this;
    }
    PB& pre (const char* type, const char* params = "", float mix = -1.0f, bool on = true)  { return fx (true, type, params, mix, on); }
    PB& post (const char* type, const char* params = "", float mix = -1.0f, bool on = true) { return fx (false, type, params, mix, on); }
    PB& gate (float thresh, float rel = 80.0f) { p.gate.enabled = true; p.gate.thresholdDb = thresh; p.gate.releaseMs = rel; return *this; }
    PB& eq (float lo, float mid, float hz, float hi) { p.eq.lowDb = lo; p.eq.midDb = mid; p.eq.midFreqHz = hz; p.eq.highDb = hi; return *this; }
    PB& in (float db)  { p.inputGainDb = db; return *this; }
    PB& out (float db) { p.outputGainDb = db; return *this; }
    PB& tempo (float bpm) { p.tempoBpm = bpm; return *this; }
};

std::string slugify (const std::string& s)
{
    std::string o;
    for (char c : s)
    {
        if (std::isalnum ((unsigned char) c)) o += (char) std::tolower ((unsigned char) c);
        else if (! o.empty() && o.back() != '-') o += '-';
    }
    while (! o.empty() && o.back() == '-') o.pop_back();
    return o;
}

void bank (std::vector<Preset>& out, const char* category, const char* slug, std::vector<PB> list)
{
    for (auto& b : list)
    {
        Preset p = b.p;
        p.category = category;
        p.id = std::string ("factory.") + slug + "." + slugify (p.name);
        for (size_t i = 0; i < p.effects.size(); ++i) p.effects[i].slotId = "slot-" + std::to_string (i + 1);
        out.push_back (std::move (p));
    }
}

