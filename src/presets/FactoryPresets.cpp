std::vector<Preset> buildFactoryPresetsUncalibrated() { return buildAll(); }

const std::vector<Preset>& factoryPresets()
{
    static const std::vector<Preset> all = []
    {
        auto v = buildAll();
        for (auto& p : v)
            for (auto& c : kCalibration)
                if (p.id == c.id) { p.outputGainDb = std::clamp (p.outputGainDb + c.db, -24.0f, 12.0f); break; }
        return v;
    }();
    return all;
}
