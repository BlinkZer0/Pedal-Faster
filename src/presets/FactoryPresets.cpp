// default; every key is checked by PresetValidator in the test suite, so a typo fails the build tests.
//
// Amp keys:     g b m t p mv s trim      (gain bass mid treble presence master sag trimDb)
// Cabinet keys: mic lo hi lvl mix         (mic position, low cut Hz, high cut Hz, level dB, wet/dry)
// Effect keys:  the ParamSpec keys from EffectRegistry.cpp (e.g. "drive=.4 tone=.6").
// Choice parameters take the choice index (see docs/PRESET_FORMAT.md for the tables).

